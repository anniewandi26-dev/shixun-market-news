/** 按 symbol id 的英文名（优先，避免 API 中文名漏映射） */
export const SYMBOL_NAME_EN_BY_ID: Record<string, string> = Object.fromEntries(
  ALL_SYMBOLS.map((s) => [
    s.id,
    SYMBOL_NAME_EN[s.name] ?? (s.yahoo.replace(/^\^/, '') || s.name),
  ]),
)

export function localizeSymbolName(name: string, locale: string, id?: string): string {
  if (locale === 'zh-CN' || locale === 'zh-TW') return name
  if (id && SYMBOL_NAME_EN_BY_ID[id]) return SYMBOL_NAME_EN_BY_ID[id]
  return SYMBOL_NAME_EN[name] ?? name
}
